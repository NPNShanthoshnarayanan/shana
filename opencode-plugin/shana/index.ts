// Shana's OpenCode plugin: tells every model call which model it REALLY is (from the request itself, not a guess),
// and steps down to a cheaper model of the same provider when the monthly budget is nearly used up.
import { Plugin } from "@opencode/plugin"
import { readFileSync } from "node:fs"

const pretty = (id: string) => id.split("/").pop()!.replace(/-/g, " ")

function budgetShare(path: string): number {
  try {
    return JSON.parse(readFileSync(path, "utf8")).share ?? 0
  } catch {
    return 0
  }
}

export default Plugin.define({
  id: "shana",
  async setup(ctx) {
    const opts = (ctx.options ?? {}) as { budget?: string; cheap?: string; downgradeAt?: number }
    const budgetFile = opts.budget ?? `${process.env.HOME}/shana/data/budget.json`
    const liveFile = budgetFile.replace(/budget\.json$/, "live.txt")

    await ctx.session.hook("context", (event: any) => {
      const id = `${event.model?.providerID}/${event.model?.id}`
      event.system.push({
        type: "text",
        text:
          `[Shana fact, from the request itself] This reply is generated by the model "${id}". ` +
          `If you name the model (a label, or when asked which model answered), use exactly "[${pretty(event.model?.id ?? "?")}]". ` +
          `Never claim to be any other model, and never say you switched models: you cannot change your own model.`,
      })
      try {
        const live = readFileSync(liveFile, "utf8").slice(0, 900)
        if (live) event.system.push({ type: "text", text: `[Shana live status, real data, refreshed every few minutes]\n${live}` })
      } catch {}
    })

    await ctx.session.hook("experimental.model.resolve", (event: any) => {
      const cheap = opts.cheap
      if (!cheap || event.kind === "title" || event.model?.id === cheap) return
      if (budgetShare(budgetFile) >= (opts.downgradeAt ?? 0.8)) {
        event.model = { providerID: event.model.providerID, id: cheap }
      }
    }, { providerID: "deepinfra" })
  },
})
