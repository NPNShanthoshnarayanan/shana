// Shana's OpenCode plugin: tells every model call which model it REALLY is (from the request itself, not a guess),
// and steps down to a cheaper model of the same provider when the monthly budget is nearly used up.
import { Plugin } from "@opencode/plugin"
import { readFileSync } from "node:fs"

const pretty = (id: string) => id.split("/").pop()!.replace(/-/g, " ")
const ORDER = /\b(fix|do)\s+(it|that|this|all|them|#\d+)\b|^\W*(yes|go ahead|just do it)\W*$/i

const BALANCE = /\b(balance|credits?|remaining (money|amount|cost|budget)|how much (is )?left)\b/i

// Text of the newest user message, whatever shape the host gives (role/info.role, string or parts).
function lastUserText(msgs: any[]): string {
  for (let k = (msgs?.length ?? 0) - 1; k >= 0; k--) {
    const m = msgs[k]
    if ((m?.role ?? m?.info?.role ?? m?.type) !== "user") continue
    const c = m.content ?? m.parts ?? m.text ?? ""
    return typeof c === "string" ? c : (Array.isArray(c) ? c : []).map((p: any) => p?.text ?? "").join(" ")
  }
  return ""
}

function budgetShare(path: string): number {
  try {
    return JSON.parse(readFileSync(path, "utf8")).share ?? 0
  } catch {
    return 0
  }
}

export default Plugin.define({
  id: "shana",
  async setup(ctx) {
    const opts = (ctx.options ?? {}) as { budget?: string; cheap?: string; downgradeAt?: number }
    const budgetFile = opts.budget ?? `${process.env.HOME}/shana/data/budget.json`
    const liveFile = budgetFile.replace(/budget\.json$/, "live.txt")

    await ctx.session.hook("context", (event: any) => {
      const id = `${event.model?.providerID}/${event.model?.id}`
      event.system.push({
        type: "text",
        text:
          `[Shana fact, from the request itself] This reply is generated by the model "${id}". ` +
          `If you name the model (a label, or when asked which model answered), use exactly "[${pretty(event.model?.id ?? "?")}]". ` +
          `Never claim to be any other model, and never say you switched models: you cannot change your own model.`,
      })
      const said = lastUserText(event.messages).trim()
      if (BALANCE.test(said)) {
        let spend = "Shana's spend count is not available right now"
        try {
          const b = JSON.parse(readFileSync(budgetFile, "utf8"))
          spend = `Shana's count of DeepInfra spend in ${b.month}: $${(+b.spent).toFixed(2)} of the $${(+b.cap).toFixed(2)} monthly cap`
        } catch {}
        event.system.push({
          type: "text",
          text:
            "[Shana fact] Answer the balance question now from this fact; run NO tool or command for it. " +
            `${spend}. Shana's key cannot read the real account balance; it is on https://deepinfra.com/dash/billing. ` +
            "Reply in 2-3 short lines with these two facts.",
        })
      }
      if (ORDER.test(said)) {
        event.system.push({
          type: "text",
          text:
            "[Shana fact] The user's last message is a direct order and counts as approval. Do the work now, in this " +
            "turn. Do not ask \"Want me to…?\" or \"Shall I track this?\". For a Shana problem use shana_issue_add " +
            "with fix_now=true or shana_issue_approve, then report the tool's RECEIPT.",
        })
      }
      try {
        const live = readFileSync(liveFile, "utf8").slice(0, 900)
        if (live) event.system.push({ type: "text", text: `[Shana live status, real data, refreshed every few minutes]\n${live}` })
      } catch {}
    })

    await ctx.session.hook("experimental.model.resolve", (event: any) => {
      const cheap = opts.cheap
      if (!cheap || event.kind === "title" || event.model?.id === cheap) return
      if (budgetShare(budgetFile) >= (opts.downgradeAt ?? 0.8)) {
        event.model = { providerID: event.model.providerID, id: cheap }
      }
    }, { providerID: "deepinfra" })
  },
})
